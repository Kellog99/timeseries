import os
import pickle
from configparser import ConfigParser

import torch

from timeseries.models.gnn.model import GNN
from .inference import get_plot


def test(
        config: ConfigParser,
        name_model: str
        ) -> None:
    print(f'{" Upload the dataframe ":=^60s}')
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    path_dataset = os.path.join(config['paths']['dataset'], f"dataframes.pkl")
    path_emb = os.path.join(config['paths']['dataset'], f"embedding_setting.pkl")

    with open(path_dataset, 'rb') as f:
        ds = pickle.load(f)

    with open(path_emb, 'rb') as f:
        emb = pickle.load(f)

    for key in ds.keys():
        config['dataset'][f'n_obs_{key}'] = f"{len(ds[key])}"

    # Match the checkpoint name generated by run.train.
    architecture = name_model[4:-3].split("_")
    config['model']['id_model'] = name_model[4:-3]
    for key, value in zip(
            ("hid_out_features1", "hid_out_features2", "num_layer1",
             "num_layer2", "nfeat_out_gnn"), architecture, strict = False
            ):
        config['model'][key] = value

    params_model = {key: config.getint('model', key) for key in (
        "in_feat", "nfeat_out_gnn", "num_layer1", "num_layer2",
        "hid_out_features1", "hid_out_features2",
    )}

    id_model = config['model']['id_model']
    # initialization 
    model = GNN(
        in_feat = params_model["in_feat"],
        past_steps = 200,
        future_steps = 65,
        future_channel = 0,
        embs = [cardinality for cardinality, _ in emb.values()],
        cat_emb_dim = config.getint('model', 'cat_emb_dim', fallback = 1),
        hidden_GNN = params_model["nfeat_out_gnn"],
        nfeat_out_gnn = params_model["nfeat_out_gnn"],
        num_layer1 = params_model["num_layer1"],
        num_layer2 = params_model["num_layer2"],
        hid_out_features1 = params_model["hid_out_features1"],
        hid_out_features2 = params_model["hid_out_features2"],
        emb = emb,
        past = 200,
        future = 65,
        device = str(device)
        )
    model.load_state_dict(torch.load(os.path.join(config['paths']['net_weights_train'], f"{name_model}")))
    model.to(device)
    print(f'{f" configuration {id_model} ":=^60s}')
    get_plot(model = model, config = config, ds = ds)
